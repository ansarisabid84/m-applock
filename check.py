import re, pathlib, sys, collections

root = pathlib.Path("app/src/main")
kt = sorted((root/"java").rglob("*.kt"))
errors, warns = [], []

# ---- 1. declarations index -------------------------------------------------
decl = {}   # fqname -> file
for f in kt:
    src = f.read_text()
    m = re.search(r'^package\s+([\w.]+)', src, re.M)
    pkg = m.group(1)
    for kind, name in re.findall(r'^(?:@\w+(?:\([^)]*\))?\s*)*(?:public |internal |private |abstract |open |sealed |data |enum |annotation )*\b(class|object|interface|enum class|fun|val|const val)\s+([A-Za-z_]\w*)', src, re.M):
        decl.setdefault(f"{pkg}.{name}", f)
    for name in re.findall(r'^\s*(?:@Composable\s*)?(?:private |internal |public |suspend )*fun\s+(?:<[^>]+>\s*)?(?:[A-Za-z_][\w.]*\.)?([A-Za-z_]\w*)\s*\(', src, re.M):
        decl.setdefault(f"{pkg}.{name}", f)
    for name in re.findall(r'^\s*(?:private |internal |public )*(?:val|var|const val)\s+([A-Za-z_]\w*)', src, re.M):
        decl.setdefault(f"{pkg}.{name}", f)

# ---- 2. internal imports resolve ------------------------------------------
for f in kt:
    for imp in re.findall(r'^import\s+(com\.sabid\.applock\.[\w.]+)', f.read_text(), re.M):
        base = imp.rsplit(".", 1)[0]
        if imp.endswith(".R") or ".R." in imp: continue
        # Generated by AGP (buildConfig = true), so it has no source file to resolve to.
        if imp.endswith(".BuildConfig"): continue
        if imp not in decl and base not in decl:
            errors.append(f"{f.relative_to(root)}: unresolved import {imp}")

# ---- 3. brace / paren balance ---------------------------------------------
for f in kt:
    src = f.read_text()
    stripped = re.sub(r'"(?:[^"\\\n]|\\.)*"', '""', src)
    stripped = re.sub(r'//.*', '', stripped)
    stripped = re.sub(r'/\*.*?\*/', '', stripped, flags=re.S)
    for open_c, close_c in [("{","}"), ("(",")")]:
        d = stripped.count(open_c) - stripped.count(close_c)
        if d: errors.append(f"{f.relative_to(root)}: unbalanced {open_c}{close_c} (delta {d})")

# ---- 4. R.* references exist ----------------------------------------------
res = root/"res"
available = collections.defaultdict(set)
for vfile in (res/"values").glob("*.xml"):
    for typ, name in re.findall(r'<(string|color|style)\s+name="([\w.]+)"', vfile.read_text()):
        available[typ].add(name.replace(".", "_"))
        available[typ].add(name)
for d in res.iterdir():
    if not d.is_dir(): continue
    typ = d.name.split("-")[0]
    if typ in ("values",): continue
    for item in d.iterdir():
        if item.is_file():
            available[typ].add(item.stem)
for f in list(kt) + [root/"AndroidManifest.xml"] + list((res).rglob("*.xml")):
    src = f.read_text()
    for typ, name in re.findall(r'R\.(\w+)\.(\w+)', src):
        if typ in ("id","attr","styleable","integer","dimen","bool","array","plurals"): continue
        if name not in available.get(typ, set()) and not (typ=="style" and name in available["style"]):
            errors.append(f"{f.relative_to(root.parent.parent)}: missing R.{typ}.{name}")
    for typ, name in re.findall(r'"@(\w+)/([\w.]+)"', src):
        if typ in ("id","android:color","integer","dimen","bool"): continue
        pool = available.get(typ, set()) | (available["mipmap"] if typ=="mipmap" else set())
        if typ == "mipmap": pool |= available.get("mipmap", set())
        if name not in pool and typ not in ("android",):
            warns.append(f"{f.name}: @{typ}/{name} not found in res/")

# ---- 5. widget layout ids used by RemoteViews ------------------------------
layout_ids = set(re.findall(r'android:id="@\+id/(\w+)"', (res/"layout"/"widget_lock.xml").read_text()))
wp = (root/"java/com/sabid/applock/service/LockWidgetProvider.kt").read_text()
for rid in re.findall(r'R\.id\.(\w+)', wp):
    if rid not in layout_ids: errors.append(f"LockWidgetProvider: R.id.{rid} not in widget_lock.xml")

# ---- 6. manifest class targets exist --------------------------------------
mf = (root/"AndroidManifest.xml").read_text()
for cls in re.findall(r'android:name="\.((?:[\w.]+))"', mf):
    if cls.startswith("Launcher."): continue
    path = root/"java/com/sabid/applock"/(cls.replace(".", "/") + ".kt")
    if not path.exists():
        errors.append(f"AndroidManifest: no source for .{cls}")

# ---- 7. no Play policy-sensitive permissions ------------------------------
# Each of these is a documented Play rejection for an app locker: QUERY_ALL_PACKAGES is
# restricted to app categories this is not one of, and the media permissions pull the app into
# the Photo and Video Permissions policy when the system document picker already covers the
# vault. A `tools:node="remove"` line is the guard, not a violation, so it is exempt.
banned = [
    "QUERY_ALL_PACKAGES",
    "READ_MEDIA_IMAGES", "READ_MEDIA_VIDEO", "READ_MEDIA_VISUAL_USER_SELECTED",
    "READ_EXTERNAL_STORAGE", "WRITE_EXTERNAL_STORAGE", "MANAGE_EXTERNAL_STORAGE",
]
# Matched per tag, not per line, since a declaration may wrap onto a second line.
for tag in re.findall(r'<uses-permission\b.*?/>', mf, re.S):
    if 'tools:node="remove"' in tag: continue
    for perm in banned:
        if f"permission.{perm}" in tag:
            errors.append(f"AndroidManifest: declares policy-sensitive {perm}")

# ---- 8. accessibility grant is only ever requested behind its disclosure --------
# Play rejected this app for "Prominent disclosure Non compliant design": it sent users to the
# Accessibility settings page with no disclosure, no affirmative consent and no second button.
# The fix routes every request through rememberAccessibilityDisclosure, and this keeps it that
# way — a new call site that opens the page directly is the exact regression that got the app
# rejected, and it is invisible in review because the code still works perfectly.
disclosure = root/"java/com/sabid/applock/ui/permissions/AccessibilityDisclosure.kt"
if not disclosure.exists():
    errors.append("AccessibilityDisclosure.kt is missing: the Play-required disclosure is gone")
for f in kt:
    if f in (disclosure, root/"java/com/sabid/applock/core/util/Permissions.kt"): continue
    src = f.read_text()
    for call in re.findall(r'Permissions\.open\([^)]*\)', src):
        if "SpecialGrant.ACCESSIBILITY" in call:
            errors.append(
                f"{f.name}: opens Accessibility settings directly; "
                "use rememberAccessibilityDisclosure() (Play prominent-disclosure policy)")

print(f"scanned {len(kt)} Kotlin files, {len(decl)} declarations")
for w in sorted(set(warns)): print("  warn:", w)
for e in sorted(set(errors)): print("  ERROR:", e)
print("RESULT:", "FAIL" if errors else "PASS")
sys.exit(1 if errors else 0)
